const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const data = new Map();
const storage = { getItem: async key => data.get(key) ?? null, setItem: async (key, value) => { data.set(key, value); } };
const code = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/game/copy-save.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText;
const loaded = { exports: {} };
new Function('require', 'module', 'exports', code)(() => storage, loaded, loaded.exports);
(async () => {
  const { copySave } = loaded.exports;
  const slots = [{slot:1, occupied:true, name:'Ada', runNumber:3}, {slot:2, occupied:false}, {slot:3, occupied:true, name:'Other'}];
  const snapshot = JSON.stringify({'@game:player_name':'Ada', '@garden:water_storage':'{"amount":3,"capacity":10}', '@game:mailbox':'{"claimed":true}'});
  data.set('game_slots', JSON.stringify(slots));
  data.set('@slot_snapshot:1', snapshot);
  data.set('@game:active_slot', '1');
  data.set('@game:player_name', 'Runtime');
  await copySave(1,2);
  assert.equal(data.get('@slot_snapshot:2'), snapshot);
  assert.equal(data.get('@slot_snapshot:1'), snapshot);
  assert.equal(data.get('@game:active_slot'), '1');
  assert.equal(data.get('@game:player_name'), 'Runtime');
  assert.deepEqual(JSON.parse(data.get('game_slots'))[1], {...slots[0], slot:2});
  const before = [...data];
  await assert.rejects(copySave(1,3), /empty/);
  await assert.rejects(copySave(1,1), /different/);
  assert.deepEqual([...data], before);
  data.set('game_slots', JSON.stringify(slots));
  data.delete('@slot_snapshot:1');
  await assert.rejects(copySave(1,2), /no saved checkpoint/);
  assert.equal(JSON.parse(data.get('game_slots'))[1].occupied, false);
  console.log('Copy Save tests passed: checkpoint, metadata, source/runtime preservation, occupied slot and missing snapshot guards.');
})().catch(error => { console.error(error); process.exitCode = 1; });
